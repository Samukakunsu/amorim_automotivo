-- Dados da oficina (sempre uma única linha, id = 1)
create table if not exists public.configuracoes (
  id                 int primary key default 1 check (id = 1),
  nome               text not null default 'Amorim Pintura Automotiva',
  endereco           text not null default 'Rua Soldado Eduardo dos Santos, nº 93 - Jatiúca - Maceió/AL',
  telefones          text not null default '(82) 99996-9591 / (82) 99811-7550',
  logo_path          text,            -- arquivo no bucket "empresa"
  fundo_recibo_path  text,            -- arquivo no bucket "empresa" (marca d'água do recibo)
  atualizado_em      timestamptz not null default now()
);

create table if not exists public.clientes (
  id             uuid primary key default gen_random_uuid(),
  nome           text not null check (length(trim(nome)) > 0),
  telefone       text,
  observacoes    text,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now()
);
create index if not exists clientes_nome_idx on public.clientes (lower(nome));

create table if not exists public.veiculos (
  id             uuid primary key default gen_random_uuid(),
  cliente_id     uuid not null references public.clientes (id) on delete restrict,
  marca          text,
  modelo         text,
  ano            text,
  placa          text not null check (length(trim(placa)) > 0),
  -- placa sem hífen/espaço e em maiúsculas: usada para achar o carro e evitar duplicados
  placa_norm     text generated always as (upper(regexp_replace(placa, '[^A-Za-z0-9]', '', 'g'))) stored,
  cor            text,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now()
);
create unique index if not exists veiculos_placa_norm_uk on public.veiculos (placa_norm);
create index if not exists veiculos_cliente_idx on public.veiculos (cliente_id);

-- Serviços que a oficina oferece (a lista usada no formulário)
create table if not exists public.catalogo_servicos (
  id            uuid primary key default gen_random_uuid(),
  nome          text not null unique,
  valor_padrao  numeric(12,2) not null default 0 check (valor_padrao >= 0),
  ativo         boolean not null default true,
  ordem         int not null default 0
);

-- Lista de avarias do carro (a lista usada no formulário e no recibo)
create table if not exists public.catalogo_avarias (
  id     uuid primary key default gen_random_uuid(),
  nome   text not null unique,
  ativo  boolean not null default true,
  ordem  int not null default 0
);

create table if not exists public.orcamentos (
  id             uuid primary key default gen_random_uuid(),
  numero         bigint generated by default as identity unique,   -- "Nº" do recibo
  cliente_id     uuid not null references public.clientes (id) on delete restrict,
  veiculo_id     uuid not null references public.veiculos (id) on delete restrict,
  entrada        date not null default current_date,
  saida          date,
  status         text not null default 'Aguardando'
                 check (status in ('Aguardando', 'Em andamento', 'Pronto', 'Entregue')),
  pecas          numeric(12,2) not null default 0 check (pecas >= 0),
  total          numeric(12,2) not null default 0 check (total >= 0),
  observacoes    text,
  foto_path      text,                         -- arquivo no bucket "fotos"
  criado_por     uuid default auth.uid(),
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now()
);
create index if not exists orcamentos_entrada_idx on public.orcamentos (entrada desc);
create index if not exists orcamentos_status_idx on public.orcamentos (status);
create index if not exists orcamentos_cliente_idx on public.orcamentos (cliente_id);
create index if not exists orcamentos_veiculo_idx on public.orcamentos (veiculo_id);

-- Serviços marcados em cada orçamento (nome e valor ficam "congelados" no orçamento)
create table if not exists public.orcamento_servicos (
  id            uuid primary key default gen_random_uuid(),
  orcamento_id  uuid not null references public.orcamentos (id) on delete cascade,
  nome          text not null,
  valor         numeric(12,2) not null default 0 check (valor >= 0),
  ordem         int not null default 0
);
create index if not exists orc_serv_orc_idx on public.orcamento_servicos (orcamento_id);

-- Avarias que o carro já tinha quando chegou
create table if not exists public.orcamento_avarias (
  orcamento_id  uuid not null references public.orcamentos (id) on delete cascade,
  nome          text not null,
  primary key (orcamento_id, nome)
);

-- ---------------------------------------------------------------------
-- 2. ATUALIZA "atualizado_em" AUTOMATICAMENTE
-- ---------------------------------------------------------------------
create or replace function public.tg_atualizado_em() returns trigger
language plpgsql as $$
begin
  new.atualizado_em := now();
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['configuracoes', 'clientes', 'veiculos', 'orcamentos'] loop
    execute format('drop trigger if exists atualizado_em on public.%I', t);
    execute format('create trigger atualizado_em before update on public.%I
                    for each row execute function public.tg_atualizado_em()', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------
-- 3. SALVAR ORÇAMENTO (tudo de uma vez, numa única transação)
--    Cria/atualiza cliente + veículo + orçamento + serviços + avarias e
--    calcula o total (serviços + peças) aqui no banco.
-- ---------------------------------------------------------------------
create or replace function public.salvar_orcamento(p jsonb) returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_cliente_id  uuid;
  v_veiculo_id  uuid;
  v_orc_id      uuid;
  v_nome        text := trim(coalesce(p #>> '{cliente,nome}', ''));
  v_fone        text := nullif(trim(coalesce(p #>> '{cliente,telefone}', '')), '');
  v_placa       text := trim(coalesce(p #>> '{veiculo,placa}', ''));
  v_placa_norm  text := upper(regexp_replace(coalesce(p #>> '{veiculo,placa}', ''), '[^A-Za-z0-9]', '', 'g'));
  v_pecas       numeric(12,2) := coalesce(nullif(p ->> 'pecas', '')::numeric, 0);
  v_status      text := coalesce(nullif(p ->> 'status', ''), 'Aguardando');
  v_entrada     date := coalesce(nullif(p ->> 'entrada', '')::date, current_date);
  v_saida       date := nullif(p ->> 'saida', '')::date;
  v_total       numeric(12,2);
  v_item        jsonb;
  v_ordem       int := 0;
begin
  if v_nome = '' then raise exception 'Informe o nome do cliente.'; end if;
  if v_placa_norm = '' then raise exception 'Informe a placa.'; end if;
  if coalesce(trim(p #>> '{veiculo,marca}'), '') = '' then raise exception 'Informe o veículo.'; end if;

  -- cliente: se veio o id, atualiza; senão procura pelo nome (+ telefone) ou cria
  if nullif(p #>> '{cliente,id}', '') is not null then
    v_cliente_id := (p #>> '{cliente,id}')::uuid;
    update clientes set nome = v_nome, telefone = v_fone where id = v_cliente_id;
    if not found then raise exception 'Cliente não encontrado.'; end if;
  else
    select id into v_cliente_id from clientes
     where lower(trim(nome)) = lower(v_nome)
       and coalesce(telefone, '') = coalesce(v_fone, '')
     order by criado_em limit 1;
    if v_cliente_id is null then
      insert into clientes (nome, telefone) values (v_nome, v_fone) returning id into v_cliente_id;
    end if;
  end if;

  -- veículo: procurado pela placa; se já existe, atualiza os dados e o dono
  select id into v_veiculo_id from veiculos where placa_norm = v_placa_norm;
  if v_veiculo_id is null then
    insert into veiculos (cliente_id, marca, modelo, ano, placa, cor)
    values (v_cliente_id, nullif(trim(p #>> '{veiculo,marca}'), ''),
            nullif(trim(p #>> '{veiculo,modelo}'), ''), nullif(trim(p #>> '{veiculo,ano}'), ''),
            v_placa, nullif(trim(p #>> '{veiculo,cor}'), ''))
    returning id into v_veiculo_id;
  else
    update veiculos set cliente_id = v_cliente_id,
           marca  = nullif(trim(p #>> '{veiculo,marca}'), ''),
           modelo = nullif(trim(p #>> '{veiculo,modelo}'), ''),
           ano    = nullif(trim(p #>> '{veiculo,ano}'), ''),
           placa  = v_placa,
           cor    = nullif(trim(p #>> '{veiculo,cor}'), '')
     where id = v_veiculo_id;
  end if;

  -- orçamento
  if nullif(p ->> 'id', '') is not null then
    v_orc_id := (p ->> 'id')::uuid;
    update orcamentos set cliente_id = v_cliente_id, veiculo_id = v_veiculo_id,
           entrada = v_entrada, saida = v_saida, status = v_status, pecas = v_pecas,
           observacoes = nullif(p ->> 'observacoes', ''), foto_path = nullif(p ->> 'foto_path', '')
     where id = v_orc_id;
    if not found then raise exception 'Orçamento não encontrado.'; end if;
    delete from orcamento_servicos where orcamento_id = v_orc_id;
    delete from orcamento_avarias where orcamento_id = v_orc_id;
  else
    insert into orcamentos (cliente_id, veiculo_id, entrada, saida, status, pecas, observacoes, foto_path)
    values (v_cliente_id, v_veiculo_id, v_entrada, v_saida, v_status, v_pecas,
            nullif(p ->> 'observacoes', ''), nullif(p ->> 'foto_path', ''))
    returning id into v_orc_id;
  end if;

  for v_item in select * from jsonb_array_elements(coalesce(p -> 'servicos', '[]'::jsonb)) loop
    v_ordem := v_ordem + 1;
    insert into orcamento_servicos (orcamento_id, nome, valor, ordem)
    values (v_orc_id, v_item ->> 'nome', coalesce(nullif(v_item ->> 'valor', '')::numeric, 0), v_ordem);
  end loop;

  insert into orcamento_avarias (orcamento_id, nome)
  select v_orc_id, x from jsonb_array_elements_text(coalesce(p -> 'avarias', '[]'::jsonb)) as x
  on conflict do nothing;

  select coalesce(sum(valor), 0) + v_pecas into v_total from orcamento_servicos where orcamento_id = v_orc_id;
  update orcamentos set total = v_total where id = v_orc_id;

  return v_orc_id;
end $$;

-- Nome e logo da oficina para a tela de login (antes de entrar no sistema)
create or replace function public.info_publica() returns json
language sql security definer set search_path = public stable as $$
  select json_build_object('nome', nome, 'logo_path', logo_path) from configuracoes where id = 1
$$;
revoke all on function public.info_publica() from public;
grant execute on function public.info_publica() to anon, authenticated;

