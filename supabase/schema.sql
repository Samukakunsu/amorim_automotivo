-- 7. TEMPO REAL: o que um aparelho altera aparece nos outros na hora
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    foreach t in array array['orcamentos', 'orcamento_servicos', 'orcamento_avarias', 'clientes',
                             'veiculos', 'catalogo_servicos', 'catalogo_avarias', 'configuracoes'] loop
      begin
        execute format('alter publication supabase_realtime add table public.%I', t);
      exception when duplicate_object then null;
      end;
    end loop;
  end if;
end $$;

-- ---------------------------------------------------------------------
-- 8. USADO PELA RESTAURAÇÃO DE BACKUP: ajusta o contador do "Nº" do orçamento
-- ---------------------------------------------------------------------
create or replace function public.reajustar_numeracao() returns void
language sql security definer set search_path = public as $$
  select setval(pg_get_serial_sequence('public.orcamentos', 'numero'),
                coalesce((select max(numero) from public.orcamentos), 0) + 1, false)
$$;
revoke all on function public.reajustar_numeracao() from public;
grant execute on function public.reajustar_numeracao() to authenticated;
