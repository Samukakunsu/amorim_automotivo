do $$
declare t text;
begin
  foreach t in array array['configuracoes', 'clientes', 'veiculos', 'catalogo_servicos',
                           'catalogo_avarias', 'orcamentos', 'orcamento_servicos',
                           'orcamento_avarias'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "somente logados" on public.%I', t);
    execute format('create policy "somente logados" on public.%I for all to authenticated
                    using (true) with check (true)', t);
  end loop;
end $$;

